import pandas as pd, numpy as np
OUT = "结果/"
J = {
 2024: dict(收入=1158819, 营业成本=974951, 销售费用=47953+70426, 净利润=44660, 现金=108350, 受限现金=7366, 短期投资=125645,
            流动资产=386698, 总资产=698234, 流动负债=299521, 总负债=384937, 股东权益=312813, 应付账款=192860, 存货=89326, 商品收入=928007),
 2025: dict(收入=1309085, 营业成本=1099057, 销售费用=83953+88176, 净利润=23142, 现金=137488, 受限现金=12137, 短期投资=75744,
            流动资产=374421, 总资产=695201, 流动负债=306072, 总负债=401418, 股东权益=293783, 应付账款=188379, 存货=95428, 商品收入=1023802)}
def jd(y):
    r = J[y]; eq = r["股东权益"]
    return pd.Series({"流动比率":r["流动资产"]/r["流动负债"], "现金比率":r["现金"]/r["流动负债"],
      "现金及短期投资覆盖率":(r["现金"]+r["短期投资"])/r["流动负债"], "资产负债率":r["总负债"]/r["总资产"],
      "总资产周转率":r["收入"]/r["总资产"], "ROA":r["净利润"]/r["总资产"], "权益乘数":r["总资产"]/eq, "ROE":r["净利润"]/eq,
      "销售净利率":r["净利润"]/r["收入"]})
pdd = pd.read_csv(OUT+"04_财务比率_拼多多.csv", index_col=0)
tab = pd.concat({"拼多多 2024":pdd["2024"], "拼多多 2025":pdd["2025"], "京东 2024":jd(2024), "京东 2025":jd(2025)}, axis=1)
tab.round(4).to_csv(OUT+"04c_两家公司财务比率对照.csv", encoding="utf-8-sig")
print("== 两家公司财务比率对照"); print(tab.round(4).to_string())
